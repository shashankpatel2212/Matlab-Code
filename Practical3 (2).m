clc;
clear all; 
close all; 
t = -2:0.01:2; 
subplot(3,2,1); 
plot(t,sin(2*pi*t));
title('sine');
subplot(3,2,2);
plot(t,sinc(t)); 
title('sinc');
subplot(3,2,3); 
plot(t,1-abs(t));
title('triangle');
subplot(3,2,4);
plot(t,abs(t)<0.5);
title('rectangular'); 
subplot(3,2,5);
plot(t,sawtooth(2*pi*t));
title('sawtooth'); 
subplot(3,2,6);
plot(t,exp(-t));
title('exponential');
